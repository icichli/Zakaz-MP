// Utility: HTML Escaping
function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// Utility: Search Highlighting
function highlightSearch(text, query) {
  if (!query || !query.trim()) return escapeHtml(text);
  const q = query.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const regex = new RegExp(`(${q})`, 'gi');
  return escapeHtml(text).replace(regex, '<span style="color: #f59e0b; background: rgba(245, 158, 11, 0.2); border-radius: 3px; padding: 0 2px;">$1</span>');
}

// Event Listeners setup
function setupEventListeners() {
  const searchInput = document.getElementById('searchInput');
  if (searchInput) {
    searchInput.addEventListener('input', (e) => handleSearch(e.target.value));
  }

  const searchClear = document.getElementById('searchClear');
  if (searchClear) {
    searchClear.addEventListener('click', resetSearch);
  }

  const dialogInput = document.getElementById('dialogInput');
  if (dialogInput) {
    dialogInput.addEventListener('keydown', (e) => {
      if (e.key === 'Enter') confirmDialogAction();
      if (e.key === 'Escape') closeDialog();
    });
  }

  // Scroll to top button visibility (appears when scrolled down > 300px)
  const btnScrollTop = document.getElementById('btnScrollTop');
  if (btnScrollTop) {
    window.addEventListener('scroll', () => {
      if (window.scrollY > 300) {
        btnScrollTop.classList.add('visible');
      } else {
        btnScrollTop.classList.remove('visible');
      }
    }, { passive: true });
  }
}

// Force refresh and clear all browser caches programmatically
async function forceAppUpdate() {
  try {
    if ('caches' in window) {
      const keys = await caches.keys();
      await Promise.all(keys.map(k => caches.delete(k)));
    }
    if ('serviceWorker' in navigator) {
      const regs = await navigator.serviceWorker.getRegistrations();
      for (const r of regs) {
        await r.unregister();
      }
    }
    localStorage.removeItem('snack_catalog_cache');
    localStorage.removeItem('snack_app_version');
    localStorage.removeItem('snack_custom_sheet_url');
    showToast('Кэш очищен. Перезагрузка...');
    setTimeout(() => {
      window.location.href = window.location.pathname + '?reload=' + Date.now();
    }, 700);
  } catch (err) {
    console.error('Force update error:', err);
    window.location.reload();
  }
}

// Register Service Worker with auto-update check on every visit
if ('serviceWorker' in navigator && (window.location.protocol === 'https:' || window.location.hostname === 'localhost' || window.location.hostname === '127.0.0.1')) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('./sw.js').then((reg) => {
      // Force check for updates from GitHub on every page load
      reg.update();

      reg.onupdatefound = () => {
        const installingWorker = reg.installing;
        if (!installingWorker) return;
        installingWorker.onstatechange = () => {
          if (installingWorker.state === 'installed' && navigator.serviceWorker.controller) {
            // New version downloaded in background! Auto-reload to apply
            showToast('🚀 Вышло обновление! Перезагрузка...');
            setTimeout(() => window.location.reload(), 1200);
          }
        };
      };
    }).catch(err => console.log('SW registration skipped:', err));

    let refreshing = false;
    navigator.serviceWorker.addEventListener('controllerchange', () => {
      if (!refreshing) {
        refreshing = true;
        window.location.reload();
      }
    });
  });
}

